function sanitizeReply(text: string): string {
  return text
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/#{2,}/g, '')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/^[•\-*]\s+/gm, '— ')
    .trim();
}

