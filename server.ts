app.post('/api/chat', async (req, res) => {
  try {
    const { messages } = req.body;
    if (!messages || !Array.isArray(messages)) {
      return res.status(400).json({ error: 'Messages array is required' });
    }

    const lastUserMessage = messages[messages.length - 1]?.content || '';

    const timeoutPromise = new Promise((_, reject) =>
      setTimeout(() => reject(new Error('TIMEOUT')), 4500)
    );

    const callPromise = (async () => {
      const contents = messages.map((m: { role: string; content: string }) => ({
        role: m.role === 'user' ? 'user' : 'model',
        parts: [{ text: m.content }]
      }));

      const response = await ai.models.generateContent({
        model: 'gemini-3.5-flash',
        contents,
        config: {
          systemInstruction: SYSTEM_INSTRUCTION,
          temperature: 0.7,
        }
      });
      return response.text;
    })();

    let reply = '';
    try {
      reply = (await Promise.race([callPromise, timeoutPromise])) as string;
    } catch {
      reply = getCuratorFallback(lastUserMessage);
    }

    res.json({ reply: reply || getCuratorFallback(lastUserMessage) });
  } catch {
    const lastUserMessage = (req.body?.messages && Array.isArray(req.body.messages))
      ? req.body.messages[req.body.messages.length - 1]?.content || ''
      : '';
    res.json({ reply: getCuratorFallback(lastUserMessage) });
  }
});

async function main() {
  const isProd = process.env.NODE_ENV === 'production';
  if (!isProd) {
    const vite = await createViteServer({
      server: { middlewareMode: true, hmr: false },
      appType: 'spa'
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static('dist'));
    app.get('*', (_req, res) => {
      res.sendFile('index.html', { root: 'dist' });
    });
  }

  app.listen(PORT, '0.0.0.0', () => {});
}

main();
